export const buildChunkPrompt = (sourceText: string): string => `あなたは英語学習用の「順送りチャンクリーディング」データを作る専門編集者です。
目的は、学習者が英文を前から意味処理し、戻り読みを減らせるようにすることです。

以下の英文を、文法と意味の自然なまとまりごとに分割し、SPARTAN READERでそのまま読み込めるJSON配列だけを出力してください。

【最重要：JSONの形式】
- 出力は、有効なJSON配列のみ。説明、見出し、注釈、Markdown、\`\`\`json、コードフェンスは絶対に付けない。
- JSONのキーと文字列を囲む引用符は、必ず半角ASCIIのダブルクォート (") を使う。スマートクォート “ ” は絶対に使わない。
- 英文そのものにダブルクォート (") が含まれる場合は、JSON内では必ず \\" のようにエスケープする。
- 末尾カンマは禁止。
- 出力前に、自分の出力がJSON.parseで解析できる正しいJSONか必ず確認する。

【出力形式】
[
  { "en": "英文チャンク", "jp": "そのチャンクを前から理解するための自然な日本語", "speaker": null }
]

【英文の分割ルール】
1. 語数より「意味のまとまり」を優先する。機械的に7語で切らない。
2. 基本は2〜7語程度。1語だけのチャンクは原則作らない。
3. ただし、自然な意味のまとまりを壊すなら8〜10語程度まで許可する。
4. 次のまとまりは、できるだけ途中で切らない。
   - 冠詞・所有格・形容詞 + 名詞
   - 助動詞 + 動詞
   - to + 動詞
   - 句動詞
   - 前置詞 + その目的語
   - 動詞 + 意味上必要な目的語・補語
   - 関係詞 + その直後の節の中心部分
   - 熟語・定型表現
5. カンマ、セミコロン、コロン、接続詞、節の境界は有力な区切り候補だが、そこで必ず切る必要はない。
6. 原文の語順・綴り・大文字小文字・句読点は変更しない。単語の追加・削除・言い換えもしない。
7. 次のような孤立した不自然なチャンクを極力作らない：
   "an object" / "each other" / "to own" / "the service."

【日本語訳 jp のルール】
1. 目的は「英文を前から理解すること」。英文チャンクに対応しつつ、日本語として自然に読める順送り訳にする。
2. 単語を機械的に置き換えた断片訳にしない。
3. 必要なら日本語の助詞や主語を補ってよい。ただし原文にない意味は足さない。
4. 各jpを上から順につないだとき、文全体の意味が自然に流れるようにする。
5. 「ある物を、」「そのサービスを。」「場所になったのです」「所有する必要があるものとして。」のような、不自然で意味が取りにくい断片訳は避ける。
6. 文末のチャンクでは、日本語として自然なら「。」「です／ます」まで含める。

【speaker】
- 会話文で話者が本文から明確に特定できる場合だけ名前を入れる。
- それ以外は必ず null。

【品質チェック】
出力する前に以下を確認する。
- JSONとして完全に有効か
- スマートクォートが混ざっていないか
- 英文中の引用符が正しくエスケープされているか
- 1語だけ・2語だけの不要な細切れが多発していないか
- 英語の重要な文法単位を途中で切っていないか
- jpが不自然な直訳の断片になっていないか
- 原文を最後まで漏れなく、順番どおりに含んでいるか

【分割例】
入力:
People do not need to buy an object if they only use it a few times a year.

望ましい出力イメージ:
[
  { "en": "People do not need to buy an object", "jp": "人は物を買う必要はありません", "speaker": null },
  { "en": "if they only use it", "jp": "それを使うのが", "speaker": null },
  { "en": "a few times a year.", "jp": "年に数回だけなら。", "speaker": null }
]

【対象の英文】
${sourceText}`;
